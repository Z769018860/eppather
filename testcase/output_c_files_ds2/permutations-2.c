void permute(int n) {
    int a[5] = {'4', '3', '2', '1', 0};
    int i[5] = {0};
    int j[5] = {0};
    int f[5] = {24};
    char c[5] = {0};
    
    for (f[0] = 24; f[0] > 0; f[0] = f[0] - 1) {
        i[0] = 1;
        for (; a[i[0]] > a[i[0] - 1]; i[0] = i[0] + 1) {}
        j[0] = 0;
        for (; a[j[0]] < a[i[0]]; j[0] = j[0] + 1) {}
        
        c[0] = a[j[0]];
        a[j[0]] = a[i[0]];
        a[i[0]] = c[0];
        
        i[0] = i[0] - 1;
        for (j[0] = 0; j[0] < i[0]; ) {
            c[0] = a[i[0]];
            a[i[0]] = a[j[0]];
            a[j[0]] = c[0];
            i[0] = i[0] - 1;
            j[0] = j[0] + 1;
        }
    }
    return;
}
