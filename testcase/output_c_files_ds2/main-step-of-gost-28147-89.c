int kboxinit(int k8[16], int k7[16], int k6[16], int k5[16], int k4[16], int k3[16], int k2[16], int k1[16], int k87[256], int k65[256], int k43[256], int k21[256])
{
    int i;
    for (i = 0; i < 256; i = i + 1)
    {
        k87[i] = (k8[(i >> 4) & 15] << 4) | k7[i & 15];
        k65[i] = (k6[(i >> 4) & 15] << 4) | k5[i & 15];
        k43[i] = (k4[(i >> 4) & 15] << 4) | k3[i & 15];
        k21[i] = (k2[(i >> 4) & 15] << 4) | k1[i & 15];
    }
    return;
}

int f(int x, int k87[256], int k65[256], int k43[256], int k21[256])
{
    x = (k87[(x >> 24) & 255] << 24) | (k65[(x >> 16) & 255] << 16) | (k43[(x >> 8) & 255] << 8) | k21[x & 255];
    x = (x << 11) | (x >> (32 - 11));
    return x;
}
