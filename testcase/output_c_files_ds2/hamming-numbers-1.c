void hamming(int n1, int n2, int q[5], int h[5], int r[5], int t[5], int i[5], int j[5]) {
    for (i[0] = 0; i[0] < 5; i[0] = i[0] + 1) {
        q[i[0]] = 0;
        h[i[0]] = 0;
        r[i[0]] = 0;
        t[i[0]] = 0;
        i[i[0]] = 0;
        j[i[0]] = 0;
    }
    
    h[0] = 1;
    q[0] = h[0];
    n1 = 1;
    n2 = 16;
    
    for (i[0] = 1; i[0] <= 5; i[0] = i[0] + 1) {
        r[0] = q[0];
        t[0] = q[n1 - 1];
        n1 = n1 - 1;
        
        for (i[1] = 1; (j[0] = i[1] * 2) < n1; ) {
            if (j[0] + 1 < n1 && q[j[0]] > q[j[0] + 1]) {
                j[0] = j[0] + 1;
            }
            if (t[0] <= q[j[0]]) {
                break;
            }
            q[i[1]] = q[j[0]];
            i[1] = j[0];
        }
        q[i[1]] = t[0];
        
        if (i[0] <= 20 || i[0] == 5) {
        }
        
        q[0] = r[0] * 2;
        q[1] = r[0] * 3;
        q[2] = r[0] * 5;
        
        for (i[2] = n1; (j[1] = i[2] / 2) && q[j[1]] > h[0]; q[i[2]] = q[j[1]], i[2] = j[1]) {
        }
        q[i[2]] = h[0];
        n1 = n1 + 1;
    }
    return;
}
