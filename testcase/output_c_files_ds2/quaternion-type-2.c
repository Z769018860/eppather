void quaternion_operations() {
    int i;
    int d[5];
    int q[3][4];
    int r[4];
    
    d[0] = 7;
    q[0][0] = 1; q[0][1] = 2; q[0][2] = 3; q[0][3] = 4;
    q[1][0] = 2; q[1][1] = 3; q[1][2] = 4; q[1][3] = 5;
    q[2][0] = 3; q[2][1] = 4; q[2][2] = 5; q[2][3] = 6;
    
    for (i = 0; i < 5; i = i + 1) {
        if (i < 3) {
            r[0] = -q[i][0]; r[1] = -q[i][1]; r[2] = -q[i][2]; r[3] = -q[i][3];
            r[0] = q[i][0]; r[1] = -q[i][1]; r[2] = -q[i][2]; r[3] = -q[i][3];
            r[0] = q[1][0] + q[2][0]; r[1] = q[1][1] + q[2][1]; 
            r[2] = q[1][2] + q[2][2]; r[3] = q[1][3] + q[2][3];
            r[0] = q[2][0] + q[1][0]; r[1] = q[2][1] + q[1][1]; 
            r[2] = q[2][2] + q[1][2]; r[3] = q[2][3] + q[1][3];
            r[0] = q[0][0] * d[0]; r[1] = q[0][1] * d[0]; 
            r[2] = q[0][2] * d[0]; r[3] = q[0][3] * d[0];
            r[0] = q[0][0] * q[0][0]; r[1] = q[0][1] * q[0][1]; 
            r[2] = q[0][2] * q[0][2]; r[3] = q[0][3] * q[0][3];
            r[0] = q[1][0] * q[2][0] - q[1][1] * q[2][1] - q[1][2] * q[2][2] - q[1][3] * q[2][3];
            r[1] = q[1][0] * q[2][1] + q[1][1] * q[2][0] + q[1][2] * q[2][3] - q[1][3] * q[2][2];
            r[2] = q[1][0] * q[2][2] - q[1][1] * q[2][3] + q[1][2] * q[2][0] + q[1][3] * q[2][1];
            r[3] = q[1][0] * q[2][3] + q[1][1] * q[2][2] - q[1][2] * q[2][1] + q[1][3] * q[2][0];
            r[0] = q[2][0] * q[1][0] - q[2][1] * q[1][1] - q[2][2] * q[1][2] - q[2][3] * q[1][3];
            r[1] = q[2][0] * q[1][1] + q[2][1] * q[1][0] + q[2][2] * q[1][3] - q[2][3] * q[1][2];
            r[2] = q[2][0] * q[1][2] - q[2][1] * q[1][3] + q[2][2] * q[1][0] + q[2][3] * q[1][1];
            r[3] = q[2][0] * q[1][3] + q[2][1] * q[1][2] - q[2][2] * q[1][1] + q[2][3] * q[1][0];
        }
    }
    return;
}
