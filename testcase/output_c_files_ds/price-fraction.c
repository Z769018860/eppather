int price_fix(int x) {
    int table[20][2] = {
        {6, 10}, {11, 18}, {16, 26}, {21, 32},
        {26, 38}, {31, 44}, {36, 50}, {41, 54},
        {46, 58}, {51, 62}, {56, 66}, {61, 70},
        {66, 74}, {71, 78}, {76, 82}, {81, 86},
        {86, 90}, {91, 94}, {96, 98}, {101, 100}
    };
    int i;
    for (i = 0; i < 20; i = i + 1) {
        if (x < table[i][0]) {
            return table[i][1];
        }
    }
    return 0;
}
