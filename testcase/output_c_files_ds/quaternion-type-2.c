int quaternion_operations() {
    int q[3][4] = {{1, 2, 3, 4}, {2, 3, 4, 5}, {3, 4, 5, 6}};
    int r[4] = {0, 0, 0, 0};
    int qd[4] = {7, 0, 0, 0};
    int d = 7;
    int i;
    int j;

    for (i = 0; i < 3; i = i + 1) {
        int norm = 0;
        for (j = 0; j < 4; j = j + 1) {
            norm = norm + q[i][j] * q[i][j];
        }
    }

    for (j = 0; j < 4; j = j + 1) {
        r[j] = -q[0][j];
    }

    r[0] = q[0][0];
    for (j = 1; j < 4; j = j + 1) {
        r[j] = -q[0][j];
    }

    for (j = 0; j < 4; j = j + 1) {
        r[j] = q[1][j] + q[2][j];
    }

    for (j = 0; j < 4; j = j + 1) {
        r[j] = q[2][j] + q[1][j];
    }

    for (j = 0; j < 4; j = j + 1) {
        r[j] = q[0][j] * d;
    }

    r[0] = q[0][0] * qd[0] - q[0][1] * qd[1] - q[0][2] * qd[2] - q[0][3] * qd[3];
    r[1] = q[0][0] * qd[1] + q[0][1] * qd[0] + q[0][2] * qd[3] - q[0][3] * qd[2];
    r[2] = q[0][0] * qd[2] - q[0][1] * qd[3] + q[0][2] * qd[0] + q[0][3] * qd[1];
    r[3] = q[0][0] * qd[3] + q[0][1] * qd[2] - q[0][2] * qd[1] + q[0][3] * qd[0];

    r[0] = q[1][0] * q[2][0] - q[1][1] * q[2][1] - q[1][2] * q[2][2] - q[1][3] * q[2][3];
    r[1] = q[1][0] * q[2][1] + q[1][1] * q[2][0] + q[1][2] * q[2][3] - q[1][3] * q[2][2];
    r[2] = q[1][0] * q[2][2] - q[1][1] * q[2][3] + q[1][2] * q[2][0] + q[1][3] * q[2][1];
    r[3] = q[1][0] * q[2][3] + q[1][1] * q[2][2] - q[1][2] * q[2][1] + q[1][3] * q[2][0];

    r[0] = q[2][0] * q[1][0] - q[2][1] * q[1][1] - q[2][2] * q[1][2] - q[2][3] * q[1][3];
    r[1] = q[2][0] * q[1][1] + q[2][1] * q[1][0] + q[2][2] * q[1][3] - q[2][3] * q[1][2];
    r[2] = q[2][0] * q[1][2] - q[2][1] * q[1][3] + q[2][2] * q[1][0] + q[2][3] * q[1][1];
    r[3] = q[2][0] * q[1][3] + q[2][1] * q[1][2] - q[2][2] * q[1][1] + q[2][3] * q[1][0];

    return;
}
