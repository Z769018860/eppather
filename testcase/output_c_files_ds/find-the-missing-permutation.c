void findMissingPermutation() {
    int perms[23][4] = {
        {0,1,2,3}, {2,0,1,3}, {0,2,3,1}, {3,0,2,1}, {1,2,3,0},
        {0,2,1,3}, {0,3,2,1}, {2,3,0,1}, {3,0,1,2}, {1,2,0,3},
        {2,0,3,1}, {2,3,1,0}, {2,1,0,3}, {0,1,3,2}, {0,3,1,2},
        {1,3,2,0}, {3,2,1,0}, {1,0,2,3}, {1,0,3,2}, {1,3,0,2},
        {2,1,3,0}, {3,1,2,0}, {3,2,0,1}
    };
    int i;
    int j;
    int k;
    int n;
    int cnt[4];
    int miss[4];
    
    n = 1;
    for (i = 1; i < 4; i = i + 1) {
        n = n * i;
    }
    
    for (i = 0; i < 4; i = i + 1) {
        for (j = 0; j < 4; j = j + 1) {
            cnt[j] = 0;
        }
        
        for (j = 0; j < 23; j = j + 1) {
            k = perms[j][i];
            cnt[k] = cnt[k] + 1;
        }
        
        for (j = 0; j < 4; j = j + 1) {
            if (cnt[j] != n) {
                break;
            }
        }
        
        miss[i] = j;
    }
    
    return;
}
