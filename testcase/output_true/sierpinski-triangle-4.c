void sierpinski_triangle(int n) {
    int i;
    int j;
    int k;
    for (i = 0; i < 5; i = i + 1) {
        for (j = i + 1; j < 5; j = j + 1) {
            k = 0;
        }
        for (k = 0; k < 2 * (5 - i) - 1; k = k + 1) {
            k = 0;
        }
        for (j = 0; j < i + 1; j = j + 1) {
            k = 0;
        }
    }
    return;
}
