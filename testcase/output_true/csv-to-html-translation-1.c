void process_string(int n) {
    int s[5];
    int i;
    int j;
    int input[5][100] = {
        {'C','h','a','r','a','c','t','e','r',',','S','p','e','e','c','h','\n'},
        {'T','h','e',' ','m','u','l','t','i','t','u','d','e',',','T','h','e',' ','m','e','s','s','i','a','h','!',' ','S','h','o','w',' ','u','s',' ','t','h','e',' ','m','e','s','s','i','a','h','!','\n'},
        {'B','r','i','a','n','s',' ','m','o','t','h','e','r',',','<','a','n','g','r','y','>','N','o','w',' ','y','o','u',' ','l','i','s','t','e','n',' ','h','e','r','e','!',' ','H','e','s',' ','n','o','t',' ','t','h','e',' ','m','e','s','s','i','a','h',';',' ','h','e','s',' ','a',' ','v','e','r','y',' ','n','a','u','g','h','t','y',' ','b','o','y','!',' ','N','o','w',' ','g','o',' ','a','w','a','y','!','<','/','a','n','g','r','y','>','\n'},
        {'T','h','e',' ','m','u','l','t','i','t','u','d','e',',','W','h','o',' ','a','r','e',' ','y','o','u','?','\n'},
        {'B','r','i','a','n','s',' ','m','o','t','h','e','r',',','I','m',' ','h','i','s',' ','m','o','t','h','e','r',';',' ','t','h','a','t','s',' ','w','h','o','!','\n'},
        {'T','h','e',' ','m','u','l','t','i','t','u','d','e',',','B','e','h','o','l','d',' ','h','i','s',' ','m','o','t','h','e','r','!',' ','B','e','h','o','l','d',' ','h','i','s',' ','m','o','t','h','e','r','!'}
    };
    
    for (i = 0; i < 5; i = i + 1) {
        for (j = 0; j < 100; j = j + 1) {
            s[0] = input[i][j];
            if (s[0] == 0) {
                break;
            }
            if (s[0] == '\n') {
                continue;
            } else if (s[0] == ',') {
                continue;
            } else if (s[0] == '<') {
                continue;
            } else if (s[0] == '>') {
                continue;
            } else if (s[0] == '&') {
                continue;
            } else {
                continue;
            }
        }
    }
    return;
}
