void fruits_func(int fruit_type) {
    int fruits_var[5];
    if (fruit_type == 0) {
        fruits_var[0] = 0;
    } else {
        if (fruit_type == 1) {
            fruits_var[0] = 1;
        } else {
            if (fruit_type == 2) {
                fruits_var[0] = 2;
            }
        }
    }
    return;
}
