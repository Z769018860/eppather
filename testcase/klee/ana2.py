# 分割数据块
lines = data.splitlines()

# 存储结果的列表
result = []
current_file = None

# 逐行处理数据
for line in lines:
    line = line.strip()
    
    # 检查是否是“Processing file: xxx.c”这一行
    if line.startswith("Processing file:"):
        current_file = line.split(":")[1].strip()  # 提取文件名
    elif line.startswith("|/"):
        # 提取表格数据行
        parts = line.split("|")
        path = parts[1].strip()
        instrs = int(parts[2].strip())
        time = float(parts[3].strip())
        icov = float(parts[4].strip())
        bcov = float(parts[5].strip())
        icount = int(parts[6].strip())
        tsolver = float(parts[7].strip())
        
        # 将提取的数据添加到结果列表中
        result.append({
            'Source File': current_file,
            'Path': path,
            'Instrs': instrs,
            'Time(s)': time,
            'ICov(%)': icov,
            'BCov(%)': bcov,
            'ICount': icount,
            'TSolver(%)': tsolver
        })

# 将提取的数据转换为 DataFrame
df = pd.DataFrame(result)

# 保存为 Excel 文件
df.to_excel("klee_analysis_summary.xlsx", index=False)

print("Excel file created successfully.")
