int get_window_coords() {
    int childx;
    int childy;
    int rootx;
    int rooty;
    int mask;
    int inwin;
    int inchildwin;
    int props[1];
    int atom_type_prop;
    int actual_format;
    int n_items;
    int bytes_after_ret;
    int d;
    
    for (d = 0; d < 1; d = d + 1) {
        props[d] = 0;
    }
    
    for (n_items = 0; n_items < 1; n_items = n_items + 1) {
        atom_type_prop = 0;
        actual_format = 0;
        bytes_after_ret = 0;
    }
    
    for (inwin = 0; inwin < 1; inwin = inwin + 1) {
        inchildwin = 0;
        rootx = 0;
        rooty = 0;
        childx = 0;
        childy = 0;
        mask = 0;
    }
    
    return;
}
