int is_inside_circles(int x, int y) {
    for (int i = 0; i < 25; i = i + 1) {
        int dx = x - circles[i][0];
        int dy = y - circles[i][1];
        int r = circles[i][2];
        if (dx * dx + dy * dy < r * r) {
            return 1;
        }
    }
    return 0;
}

void montecarlo() {
    int x_min = 2147483647;
    int x_max = -2147483648;
    int y_min = 2147483647;
    int y_max = -2147483648;

    for (int i = 0; i < 25; i = i + 1) {
        int cx = circles[i][0];
        int cy = circles[i][1];
        int r = circles[i][2];
        int x1 = cx - r;
        int x2 = cx + r;
        int y1 = cy - r;
        int y2 = cy + r;
        if (x1 < x_min) {
            x_min = x1;
        }
        if (x2 > x_max) {
            x_max = x2;
        }
        if (y1 < y_min) {
            y_min = y1;
        }
        if (y2 > y_max) {
            y_max = y2;
        }
    }

    int bbox_area = (x_max - x_min) * (y_max - y_min);
    int to_try = 65536;
    int n_tries = 0;
    int n_hits = 0;

    for (;;) {
        int x = x_min + (rand() % (x_max - x_min));
        int y = y_min + (rand() % (y_max - y_min));
        n_hits = n_hits + is_inside_circles(x, y);
        n_tries = n_tries + 1;

        if (n_tries == to_try) {
            int area = (bbox_area * n_hits) / n_tries;
            int r = n_hits / n_tries;
            int s = (area * r * (1 - r)) / n_tries;
            if (s * 3 <= 1000) {
                break;
            }
            to_try = to_try * 2;
        }
    }
    return;
}
