int x_window_example(void) {
    int d;
    int w;
    int e_type;
    int s;
    int msg[13] = {'H','e','l','l','o',',',' ','W','o','r','l','d','!'};
    int i;
    int j;
    int k;
    
    d = 0;
    if (d == 0) {
        return;
    }
    
    s = 0;
    w = 0;
    
    for (;;) {
        e_type = 0;
        if (e_type == 1) {
            for (i = 20; i < 30; i = i + 1) {
                for (j = 20; j < 30; j = j + 1) {
                    k = 0;
                }
            }
            for (i = 0; i < 13; i = i + 1) {
                k = msg[i];
            }
        }
        if (e_type == 2) {
            break;
        }
    }
    
    return;
}
