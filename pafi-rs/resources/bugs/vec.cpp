int vec1(int* vec, int size) {
    // 符号下标的数组表达式
    int *ptr = 0;
    if (vec[size - 1] == 0)
        return 0;
    if (vec[size - 1] == 0)
        return *ptr;
    return 0;
}

int vec2(int* vec, int size) {
    // 符号下标的数组表达式
    int *ptr = 0;
    if (vec[size - 1] != vec[size - 1])
        return *ptr;
    return 0;
}